/**
 * EXPO CONFIG PLUGIN — a live system font-size change re-measures text (A3 item 3, batch 1b, 2026-10-11).
 *
 * WHY. react-native 0.81.5 ships `enableFontScaleChangesUpdatingLayout()` = false
 * (ReactNativeFeatureFlagsDefaults.kt:64). With it off, a font-size change made while the app
 * runs leaves every Text MEASURED at the process's first scale and DRAWN at the new one:
 * measured on the emulator, 1.0 -> 1.3 live clipped `ผู้ขาย` to `ผ้` and `เปลี่ยน` to `เปลี่`,
 * until the process restarted (OPEN_ITEMS.md § Verification gaps, first line). With it on,
 * ReactHostImpl.onConfigurationChanged re-initialises DisplayMetricsHolder and a surface takes
 * the current fontScale (ReactSurfaceImpl.kt:211-214).
 *
 * HOW. `android/` is generated by `npx expo prebuild` and must not be hand-edited (app.json
 * extra._comment_native), so this plugin edits the GENERATED MainApplication.kt: right after
 * `loadReactNative(this)` — which installs the stable flag provider — it force-overrides the
 * flags with a provider IDENTICAL to ReactNativeFeatureFlagsOverrides_RNOSS_Stable_Android
 * (fabric, bridgeless and turbo modules on; that class is final, so its four overrides are
 * reproduced on the same open base, ReactNativeNewArchitectureFeatureFlagsDefaults) plus ONE
 * flag: enableFontScaleChangesUpdatingLayout = true. `dangerouslyForceOverride` is used
 * because `override` may only be called once and loadReactNative already called it; it
 * returns the flags read before the call, which are logged, never thrown.
 *
 * The insertion is idempotent (a marker comment) and REFUSES if `loadReactNative(this)` is not
 * found, so a template change upstream fails the prebuild loudly instead of shipping without
 * the flag.
 */
const { withMainApplication } = require("@expo/config-plugins");

const MARKER = "// recycle: enableFontScaleChangesUpdatingLayout (plugins/withFontScaleLayout.js)";
const ANCHOR = "loadReactNative(this)";

const IMPORTS = [
  "import com.facebook.react.internal.featureflags.ReactNativeFeatureFlags",
  "import com.facebook.react.internal.featureflags.ReactNativeNewArchitectureFeatureFlagsDefaults",
];

const OVERRIDE = `
    ${MARKER}
    val readBeforeOverride = ReactNativeFeatureFlags.dangerouslyForceOverride(
      object : ReactNativeNewArchitectureFeatureFlagsDefaults(true) {
        // = ReactNativeFeatureFlagsOverrides_RNOSS_Stable_Android(true, true, true)
        override fun useFabricInterop(): Boolean = true
        override fun enableFabricRenderer(): Boolean = true
        override fun useTurboModules(): Boolean = true
        override fun useShadowNodeStateOnClone(): Boolean = true
        // + the one flag this plugin exists for
        override fun enableFontScaleChangesUpdatingLayout(): Boolean = true
      }
    )
    if (readBeforeOverride != null) {
      android.util.Log.w("recycle", "feature flags read before the font-scale override: $readBeforeOverride")
    }`;

function addFontScaleOverride(src) {
  if (src.includes(MARKER)) return src;
  if (!src.includes(ANCHOR)) {
    throw new Error(`withFontScaleLayout: "${ANCHOR}" not found in MainApplication.kt — the template changed; refusing to build without the flag`);
  }
  let out = src.replace(ANCHOR, ANCHOR + OVERRIDE);
  for (const imp of IMPORTS) {
    if (!out.includes(imp)) out = out.replace(/^(package [^\n]+\n)/m, `$1\n${imp}`);
  }
  return out;
}

module.exports = function withFontScaleLayout(config) {
  return withMainApplication(config, (cfg) => {
    if (cfg.modResults.language !== "kt") {
      throw new Error("withFontScaleLayout: MainApplication is not Kotlin; refusing");
    }
    cfg.modResults.contents = addFontScaleOverride(cfg.modResults.contents);
    return cfg;
  });
};
module.exports.addFontScaleOverride = addFontScaleOverride;
module.exports.MARKER = MARKER;
